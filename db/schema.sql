CREATE TABLE LOGIN (
  ID VARCHAR2(256 BYTE) NOT NULL PRIMARY KEY,
  PASSWORD VARCHAR2(256 BYTE) NOT NULL,
  NAME VARCHAR2(256 BYTE) NOT NULL,
  EMAIL VARCHAR2(256 BYTE),
  OK NUMBER(1) DEFAULT 1,
  SALT VARCHAR2(256 BYTE)
);
CREATE TABLE BBS (
  NO NUMBER(10) NOT NULL PRIMARY KEY,
  TITLE VARCHAR2(255), WRITER VARCHAR2(255), CONTENT VARCHAR2(4000),
  REGDATE DATE, OK NUMBER(1) DEFAULT 1, COUNT NUMBER DEFAULT 0,
  FILENAME VARCHAR2(255), ORIGINAL_FILENAME VARCHAR2(255)
);
CREATE SEQUENCE BBS_SEQ START WITH 1 INCREMENT BY 1;
CREATE TABLE BBSW (
  NO NUMBER(10) NOT NULL PRIMARY KEY,
  BBS_NO NUMBER(10) NOT NULL,
  WRITER VARCHAR2(255), CONTENT VARCHAR2(4000), REGDATE DATE DEFAULT SYSDATE,
  WCOUNT NUMBER DEFAULT 0, OK NUMBER(1) DEFAULT 1, PARENT_NO NUMBER(10),
  CONSTRAINT FK_BBSW_BBS FOREIGN KEY (BBS_NO) REFERENCES BBS(NO)
);
CREATE SEQUENCE BBSW_SEQ START WITH 1 INCREMENT BY 1;
CREATE TABLE BBSW_REACTION (
  WNO NUMBER(10) NOT NULL, USER_ID VARCHAR2(255) NOT NULL,
  REACTION VARCHAR2(10) NOT NULL, REGDATE DATE DEFAULT SYSDATE,
  PRIMARY KEY (WNO, USER_ID),
  CONSTRAINT FK_BBSW_REACTION_COMMENT FOREIGN KEY (WNO) REFERENCES BBSW(NO),
  CONSTRAINT CK_BBSW_REACTION_TYPE CHECK (REACTION IN ('GOOD', 'BAD'))
);
CREATE TABLE BBS_REACTION (
  BBS_NO NUMBER NOT NULL, USER_ID VARCHAR2(20) NOT NULL,
  REACTION VARCHAR2(10) NOT NULL, REGDATE DATE DEFAULT SYSDATE,
  CONSTRAINT PK_BBS_REACTION PRIMARY KEY (BBS_NO, USER_ID)
);
